def test_tutorial_verify_block_helpers_via_runpy() -> None:
    root = repo_root()
    ns = runpy.run_path(str(root / "scripts" / "check_tutorial_verify_blocks.py"))
    sample = "## 验证命令\n\n```bash\necho ok\n```\n\n## 期望输出\n\n- exit 0\n"
    assert ns["_section_after"](sample, ns["VERIFY_HEADINGS"]) is not None
    assert ns["_has_fence"](ns["_section_after"](sample, ns["VERIFY_HEADINGS"]))
